                                </h3>
                                <p>
                                   Each group gives a 5-minute report from Session 3, then works on Tasks 4a-4c. 
                                </p>
                                <p><strong>Small-group work. No presentations. </strong></p>
                                <p>Task 4a - Decision Pathway (20 min) </p>
                                <p><strong>Question: </strong> Given the conditions and constraints, what should be pursued now? </p>
                                <ul>
                                    <li>Who needs to act, for whom, and through what process? </li>
                                    <li>Why is this pathway preferable to the most plausible alternative? </li>
                                </ul>
                                <p>Do not pre-judge the answer. When comparing pathways, use three tests: Credible (supported by evidence and reasoning), Acceptable (responsive to relevant interests), and Feasible (politically, institutionally, technically, and practically possible). </p>
                                <p><strong>Expected output: </strong><span>One or two tools/processes to explore, use, or test before January 2027. </span></p>
                                <p>Task 4c - Metrics (20 min) </p>
                                <p>Identify a small number of measurables, trackable indicators linked directly to the proposed pathway and expected outcomes. </p>
                                <p><strong>Illustrative metrics: </strong>Reliability, equity, political feasibility, environmental health, and near-term progress. </p>
                                <p><strong>Expected output:</strong><span>A small set of measurable indicators showing whether the pathway is moving in a desirable direction. </span></p>
