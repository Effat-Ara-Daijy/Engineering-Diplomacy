                                    <strong>Small-group work. No presentations. </strong>  Each group is comprised of eight members (ideally, two from each of the stakeholder groups: knowledge community, decision-making community, resource community, and impacted community), a facilitator and a transcriber. Each group will prepare a summary of their conversation. This summary will be presented by the group facilitator at the beginning of Session 4. 
