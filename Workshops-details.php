                        <span class="session-type">
                            SESSION 04 · WORKING LUNCH
                        </span>
                        <h3>
                            Decision Pathway, Tools &amp; Processes, and Metrics | 1:00-3:00 PM (working lunch)
                        </h3>
                        <p>
                            Each group gives a 5-minute report from Session 3, then works on Tasks 4a-4c.
                        </p>
                        <p><strong>Small-group work. No presentations.</strong></p>
                        <p>Task 4a - Decision Pathway (30 min)</p>
                        <p><strong>Question:</strong> Given the capacity and constraints, what decision pathway is actionable now? Who needs to act, for whom, and through what process?</p>
                        <p><strong>Important: </strong> Do not pre-judge the choice architecture. Fixed allocation, flexible allocation, conditional
                        renewal, or other formulations are candidate pathways to assess, not prescribed answers.</p>
                        <p><strong>Expected output: </strong>One or more defensible pathways with a brief rationale.</p>
                        <p>Task 4b - Tools &amp; Processes (30 min)</p>
                        <p>Choose one or two tools/processes that could make the pathway more actionable and explain how they
                        would change interaction, learning, coordination, or decision quality.</p>
                        <p><strong>Illustrative options:</strong> joint fact-finding; augmentation options; flexible/adaptive treaty clauses; scenario
                        modeling; mutual-gains negotiation.</p>
                        <p><strong>Expected output:</strong>One or two tools/processes to explore, use, or test before January 2027.</p>
                        <p>Task 4c - Metrics (30 min)</p>
                        <p>Identify a small number of measurable, trackable indicators linked directly to the proposed pathway and expected outcomes.</p>
                        <p><strong> Illustrative metrics:</strong> flow reliability, equity, political feasibility, environmental health, and near-term progress.</p>
                        <p>Each group will prepare a summary of their conversation. This summary will be presented by the group
                                facilitator at the beginning of Session 4.</p>
                        <p><strong>Expected output:</strong> A small set of measurable indicators showing whether the pathway is moving in a desirable direction.</p>


