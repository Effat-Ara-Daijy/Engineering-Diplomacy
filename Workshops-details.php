                        <h3>
                            Conditions, Capacity, Constraints, and Enabling Conditions | Noon-1:00 PM (60 min)
                        </h3>

                        <p>
                            <strong>Small-group work. No presentations.</strong>  Each group is comprised of eight members (ideally, two from each
                            of the stakeholder groups: knowledge community, decision-making community, resource community,
                            and impacted community), a facilitator and a transcriber. Each group will prepare a summary of their
                            conversation. This summary will be presented by the group facilitator at the beginning of Session 4.
                        </p>
                        <p><strong> Task 3a (30 min):</strong> What is contested (access, allocation, use, risk)? What is scientifically known, societally
                        contested, and economically and politically feasible?</p>
                        <p><strong> Task 3b (30 min):</strong> What capacities, constraints, and enabling conditions matter most? What helps
                        explain why the problem persists?</p>
                        <p><strong>Expected output: </strong><span>A short list of key conditions, capacities, constraints, and stakeholder considerations
                        that can facilitate or hinder actionability of the decision space.</span> </p>

